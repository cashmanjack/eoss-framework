"""Queue 15: does the model's prediction move the same way as the measured launch time when the kNN any hit heap insertion is replaced by a register heap? CPU only.
Run: /usr/bin/python3 -I model/q15/knn_fix_model.py   writes model/results_knn_fix_4070ti.md.  Forms as in model/q14/FORM.md and model/q15/FORM_handoff.md; c0 = 184 (floor form, 12 RTNN fit), 112/74 for the other forms, miss term as in q14. Nothing refitted on the new build."""
import os, sys, re, statistics as st, csv, io, contextlib
import numpy as np
H = os.path.expanduser('~/eoss'); sys.path.insert(0, H + '/model'); os.chdir(H)
import callback_cost as CB
L = []
def P(*a):
    t = ' '.join(str(x) for x in a); print(t); L.append(t)
GHZ, NSM = 2.5e9, 60; LG = H + '/notes/q15/logs/'; NC = H + '/notes/q15/ncu/'
act = [200000, 200000, 200000, 197660]; qpr = [1.134, 1.919, 8.145, 56.026]; bef = [0.187, 0.203, 0.284, 0.734]
def logs(v, m):
    d = {}
    for rep in (1, 2, 3):
        t = open(LG + 'knnfix_%s_%s_%d.log' % (v, m, rep)).read()
        for r, ms in re.findall(r'ROUND (\d) active \d+ radius \S+ KERNEL_MS (\S+)', t): d.setdefault(('ms', int(r)), []).append(float(ms))
        for m2 in re.finditer(r'CBK round (\d) warps \d+ total_warp_cycles \d+ trace_warp_cycles \d+ f0_cycles (\d+) f0_calls (\d+)', t): (int(m2.group(3)) and d.setdefault(('L', int(m2.group(1))), []).append((int(m2.group(2)) / int(m2.group(3)), int(m2.group(3)))))
    return d
def w_of(v, r):
    for row in csv.reader(open(NC + 'occ_%s_r%d.csv' % (v, r))):
        if len(row) > 14 and row[12] == 'sm__warps_active.avg.per_cycle_active': return float(row[14])
D = {v: dict(off=logs(v, 'off'), ld=logs(v, 'loaded'), sm=logs(v, 'small')) for v in ('orig', 'reg')}
forms = ['floor (F131)', 'max(floor, unloaded latency) (F133)', 'floor + hand off (q15 primary, probe N, c0 74)', 'loaded latency (consistency)']
c0 = [184.0, 110.0, 74.0, 74.0]
P('| round | build | measured ms | ' + ' | '.join(forms) + ' | warp instructions per call (callback functions, call weighted) | L1 tag requests + local accesses per call (same) |'); P('|---|---|---|' + '---|' * (len(forms) + 2))
pred = {}
for r in range(1, 5):
    for v in ('orig', 'reg'):
        N = act[r - 1]; warps = N / 32; W = w_of(v, r - 1); T = CB.term(NC + 'knn_%s_r%d' % (v, r - 1), warps, 'max'); fl = T['cycles']
        calls = st.median(c[1] for c in D[v]['ld'][('L', r)]); Lld = st.median(c[0] for c in D[v]['ld'][('L', r)]); Lun = st.median(c[0] for c in D[v]['sm'][('L', r)])
        miss = max(bef[r - 1] * 1e-3 * 1.5e11 / act[r - 1] - (110.0 + 4.9 * (qpr[r - 1] + 1)), 0)
        Tcb = [fl, max(fl, Lun * calls / (NSM * W)), fl + 875.0 * calls / (NSM * W), max(fl, Lld * calls / (NSM * W))]
        ms = lambda t, c: (c + t * NSM / N + miss) * N / (NSM * GHZ) * 1e3
        p = [ms(Tcb[i], c0[i]) for i in range(4)]; pred[(r, v)] = p; m = st.median(D[v]['off'][('ms', r)])
        ins = sum(x[2] * x[1] for x in T['parts']) / sum(x[1] for x in T['parts']); mem = sum(x[4] * x[1] for x in T['parts']) / sum(x[1] for x in T['parts'])
        pred[(r, v, 'm')] = m
        P('| %d | %s | %.3f | ' % (r, v, m) + ' | '.join('%.3f (%+.2f)' % (x, np.log(x / m)) for x in p) + ' | %.0f | %.0f |' % (ins, mem))
P('\n## Speedup of the register heap over the original (launch time ratio, probes off), measured and predicted')
P('| round | measured | ' + ' | '.join(forms) + ' |'); P('|---|---|' + '---|' * len(forms))
errs = [[] for _ in forms]; tot_m = [0, 0]; tot_p = [[0, 0] for _ in forms]
for r in range(1, 5):
    sm = pred[(r, 'orig', 'm')] / pred[(r, 'reg', 'm')]; sp = [pred[(r, 'orig')][i] / pred[(r, 'reg')][i] for i in range(4)]
    for i in range(4): errs[i].append(np.log(sp[i] / sm)); tot_p[i][0] += pred[(r, 'orig')][i]; tot_p[i][1] += pred[(r, 'reg')][i]
    tot_m[0] += pred[(r, 'orig', 'm')]; tot_m[1] += pred[(r, 'reg', 'm')]
    P('| %d | %.2fx | ' % (r, sm) + ' | '.join('%.2fx' % x for x in sp) + ' |')
P('| rounds 1 to 4 total | %.2fx | ' % (tot_m[0] / tot_m[1]) + ' | '.join('%.2fx' % (a / b) for a, b in tot_p) + ' |')
P('| rms log error of the speedup | | ' + ' | '.join('%.2f' % np.sqrt(np.mean(np.square(e))) for e in errs) + ' |')
open(H + '/model/results_knn_fix_4070ti.md', 'w').write('# kNN any hit register heap: model prediction against measurement (queue 15, 4070 Ti), generated by model/q15/knn_fix_model.py\n\n' + '\n'.join(L) + '\n')
