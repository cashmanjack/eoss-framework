// BITTU compute mode: an NVBit tool that counts, times and records the TTU groups of kernels with TTU code that we run directly (not OptiX's own kernels:
// NVBit never sees those, Finding 60). Inject with CUDA_INJECTION64_PATH (ttu/harness/setup3/run.py --inject, or bittu/compute/run_bittu.py).
//
// What it does for the function ttu_one (any kernel whose name contains BITTU_KERNEL, default ttu_one):
//   1. NVBit hides TTU instructions from its instruction list (Finding 60): the group is the one gap in the offsets. The group's bytes are read from BITTU_GROUP_FILE
//      (cut by run_bittu.py from the checked binary, same sha256) because the code is not readable through NVBit's address. The gap must equal BITTU_GROUP_OFF / BITTU_GROUP_LEN.
//   2. The bytes are decoded with the EoSS SM89 tables (ttu_tables.h, generated by gen_tables.py): one TTUOPEN first, TTUMACROFUSE N = number of TTU instructions after it, all of them
//      TTUST / TTUGO / TTULD, bit 74 on the last TTULD and only there, even register pairs. Anything else: not instrumented.
//   3. Probes (NVBit calls, no TTU instruction is moved or touched): bittu_cal + bittu_pre after the instruction before TTUOPEN, bittu_post after the instruction that follows the group
//      (the one that waits for the results). Per thread and group instance: clock before and after, two clocks at the same point (probe cost), the 8 ray registers (stores 0x40 and 0x50), the
//      TTULD destination registers, the active masks, the instance count.
//   4. After every launch: summary (threads, instances, probe overhead o = median(t0b - t0a), measured median(t1 - t0b), corrected = measured - o) and the first BITTU_PRINT records.
// Env: BITTU_OUT (report file, default stderr), BITTU_PRINT (records printed, default 64), BITTU_MODE=off (decode only, no probes), BITTU_KERNEL.
#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <stdlib.h>
#include <algorithm>
#include <string>
#include <set>
#include <vector>
#include "nvbit_tool.h"
#include "nvbit.h"
#include "utils/utils.h"
#include "bittu_rec.h"
#include "ttu_tables.h"

struct Inst { const TtuClass *c; uint64_t lo, hi; int pg, pg_not, offset, rb, rc, rd, rd2, close; };
struct Group { bool ok = false; int fuse = 0; std::vector<Inst> ins; std::string why; std::vector<int> ray_regs, res_regs; };

static FILE *out = stderr;
static int print_n = 64, off_mode = 0, launches = 0;
static std::string kernel = "ttu_one";
static std::set<CUfunction> done;
static BittuRec *g_rec = nullptr, *h_rec = nullptr; static int *g_nseen = nullptr, *h_nseen = nullptr; static int g_nth = 0; static bool g_ready = false; static CUfunction g_func = nullptr;

static uint64_t field(const Inst &i, TtuField f) {   // bits [hi:lo] of the 128 bit instruction
    if (f.hi < 0) return 0; uint64_t v = 0;
    for (int b = f.lo; b <= f.hi; ++b) v |= (uint64_t)(((b < 64 ? i.lo >> b : i.hi >> (b - 64)) & 1)) << (b - f.lo);
    return v;
}

static Group decode(const std::vector<uint8_t> &code) {
    Group g; const size_t n = code.size() / 16; if (code.size() % 16 || n < 4) { g.why = "length"; return g; }
    for (size_t k = 0; k < n; ++k) {
        Inst i{}; memcpy(&i.lo, &code[16 * k], 8); memcpy(&i.hi, &code[16 * k + 8], 8);
        const unsigned op = i.lo & 0xfff; i.c = nullptr;
        for (int c = 0; c < TTU_NCLASSES; ++c) if (TTU_CLASSES[c].op12 == op) i.c = &TTU_CLASSES[c];
        if (!i.c) { g.why = "instruction " + std::to_string(k) + " is not TTU"; return g; }
        i.pg = (int)field(i, i.c->pg); i.pg_not = (int)field(i, i.c->pg_not); i.offset = (int)field(i, i.c->offset);
        i.rb = i.c->rb.hi >= 0 ? (int)field(i, i.c->rb) : -1; i.rc = i.c->rc.hi >= 0 ? (int)field(i, i.c->rc) : -1;
        i.rd = i.c->rd.hi >= 0 ? (int)field(i, i.c->rd) : -1; i.rd2 = i.c->rd2.hi >= 0 ? (int)field(i, i.c->rd2) : -1; i.close = i.c->close.hi >= 0 ? (int)field(i, i.c->close) : 0;
        g.ins.push_back(i);
    }
    const char *nm = g.ins[0].c->name; if (strcmp(nm, "TTUOPEN") || strcmp(g.ins[1].c->name, "TTUMACROFUSE")) { g.why = "does not start with TTUOPEN, TTUMACROFUSE"; return g; }
    g.fuse = (int)field(g.ins[1], g.ins[1].c->fuse);
    if ((size_t)g.fuse != n - 2) { g.why = "fuse count " + std::to_string(g.fuse) + " != " + std::to_string(n - 2) + " TTU instructions after it"; return g; }
    int closes = 0, opens = 0; std::vector<int> ray40, ray50;
    for (size_t k = 0; k < n; ++k) {
        const Inst &i = g.ins[k]; const std::string c = i.c->name; opens += c == "TTUOPEN"; closes += i.close;
        if (c == "TTUOPEN" && k) { g.why = "second TTUOPEN"; return g; }
        if (c == "TTUST" || c == "TTULD") {
            for (int r : {c == "TTUST" ? i.rb : i.rd, c == "TTUST" ? i.rc : i.rd2}) if (r != 255 && (r < 0 || r % 2)) { g.why = "odd or missing register pair base"; return g; }
        }
        if (c == "TTUST" && (i.offset == 0x40 || i.offset == 0x50)) {   // low 64 bits = Rc pair, high 64 bits = Rb pair: origin x y / z tmin, direction x y / z tmax
            std::vector<int> &v = i.offset == 0x40 ? ray40 : ray50; v = {i.rc, i.rc + 1, i.rb, i.rb + 1};
        }
        if (c == "TTULD") for (int r : {i.rd, i.rd2}) if (r != 255 && (int)g.res_regs.size() + 2 <= BITTU_MAXR) { g.res_regs.push_back(r); g.res_regs.push_back(r + 1); }
    }
    const Inst &last = g.ins[n - 1];
    if (strcmp(last.c->name, "TTULD") || !last.close || closes != 1 || last.pg != 7 || last.pg_not) { g.why = "bit 74 is not on exactly the last, unpredicated TTULD"; return g; }
    if (opens != 1) { g.why = "TTUOPEN count"; return g; }
    if (ray40.size() == 4 && ray50.size() == 4) { g.ray_regs = ray40; g.ray_regs.insert(g.ray_regs.end(), ray50.begin(), ray50.end()); }
    g.ok = true; return g;
}

static void print_group(const Group &g, size_t at) {
    for (size_t k = 0; k < g.ins.size(); ++k) {
        const Inst &i = g.ins[k]; const std::string c = i.c->name;
        fprintf(out, "    +0x%04zx %s%s%s", at + 16 * k, i.pg == 7 && !i.pg_not ? "" : (i.pg_not ? "@!P" : "@P"), i.pg == 7 && !i.pg_not ? "" : std::to_string(i.pg).c_str(), c.c_str());
        if (c == "TTUMACROFUSE") fprintf(out, " %d", g.fuse);
        if (c == "TTUST") fprintf(out, " 0x%x, R%d, R%d", i.offset, i.rb, i.rc);
        if (c == "TTULD") fprintf(out, " R%d, R%d, 0x%x%s", i.rd, i.rd2, i.offset, i.close ? " .CLOSE (bit 74)" : "");
        fprintf(out, "\n");
    }
}

void nvbit_at_init() {
    if (getenv("BITTU_OUT")) out = fopen(getenv("BITTU_OUT"), "w");
    if (getenv("BITTU_PRINT")) print_n = atoi(getenv("BITTU_PRINT"));
    if (getenv("BITTU_KERNEL")) kernel = getenv("BITTU_KERNEL");
    off_mode = getenv("BITTU_MODE") && !strcmp(getenv("BITTU_MODE"), "off");
    fprintf(out, "bittu compute: kernel '%s', mode %s\n", kernel.c_str(), off_mode ? "off (decode only)" : "probes");
}

static void collect(uint8_t b, void *u) { ((std::vector<uint8_t> *)u)->push_back(b); }

static void instrument(CUcontext ctx, CUfunction f, int nth) {
    std::vector<CUfunction> fs = nvbit_get_related_functions(ctx, f); fs.push_back(f);
    for (CUfunction fn : fs) {
        if (!done.insert(fn).second) continue;
        const char *name = nvbit_get_func_name(ctx, fn); if (!strstr(name, kernel.c_str())) continue;
        const std::vector<Instr *> &ins = nvbit_get_instrs(ctx, fn); int gk = -1;
        for (size_t k = 0; k + 1 < ins.size(); ++k) if (ins[k + 1]->getOffset() - ins[k]->getOffset() > 16) gk = gk == -1 ? (int)k : -2;
        if (gk < 0) { fprintf(out, "  %s: %s\n", name, gk == -1 ? "no hidden instructions" : "more than one gap: refusing to instrument"); continue; }
        Instr *before = ins[gk], *after = ins[gk + 1];
        const uint32_t g0 = before->getOffset() + 16, glen = (after->getOffset() - g0) / 16;
        const char *gf = getenv("BITTU_GROUP_FILE"), *eo = getenv("BITTU_GROUP_OFF"), *el = getenv("BITTU_GROUP_LEN");
        if (!gf || !eo || !el || strtoul(eo, 0, 0) != g0 || strtoul(el, 0, 0) != glen) { fprintf(out, "  %s: gap +0x%x, %u instructions does not match BITTU_GROUP_OFF/LEN/FILE: refusing to instrument\n", name, g0, glen); continue; }
        std::vector<uint8_t> code(16 * glen); FILE *fp = fopen(gf, "rb"); if (!fp || fread(code.data(), 1, code.size(), fp) != code.size()) { fprintf(out, "  cannot read %s\n", gf); continue; } fclose(fp);
        Group g = decode(code);
        fprintf(out, "  %s: group at +0x%x, %u instructions: %s%s\n", name, g0, glen, g.ok ? "decoded, complete fused group" : "NOT a complete group: ", g.ok ? "" : g.why.c_str());
        if (g.ok) print_group(g, g0);
        if (!g.ok || off_mode) continue;
        fprintf(out, "  ray registers:"); for (int r : g.ray_regs) fprintf(out, " R%d", r); fprintf(out, "\n  result registers:"); for (int r : g.res_regs) fprintf(out, " R%d", r); fprintf(out, "\n");
        fprintf(out, "  probes: bittu_cal + bittu_pre after +0x%04x, bittu_post after +0x%04x\n", before->getOffset(), after->getOffset());
        const size_t nrec = (size_t)nth * BITTU_INST;
        cudaMalloc(&g_rec, nrec * sizeof(BittuRec)); cudaMalloc(&g_nseen, (size_t)nth * sizeof(int)); h_rec = (BittuRec *)malloc(nrec * sizeof(BittuRec)); h_nseen = (int *)malloc((size_t)nth * sizeof(int)); /* device memory, not managed: first touch page faults of managed memory cost 1.8 M cycles in the first probe */ g_nth = nth; g_func = fn;
        nvbit_insert_call(before, "bittu_cal", IPOINT_AFTER); nvbit_add_call_arg_guard_pred_val(before);
        nvbit_add_call_arg_const_val64(before, (uint64_t)g_rec); nvbit_add_call_arg_const_val64(before, (uint64_t)g_nseen); nvbit_add_call_arg_const_val32(before, nth);
        nvbit_insert_call(before, "bittu_pre", IPOINT_AFTER); nvbit_add_call_arg_guard_pred_val(before);
        nvbit_add_call_arg_const_val64(before, (uint64_t)g_rec); nvbit_add_call_arg_const_val64(before, (uint64_t)g_nseen); nvbit_add_call_arg_const_val32(before, nth);
        nvbit_add_call_arg_const_val32(before, (int)g.ray_regs.size()); for (int r : g.ray_regs) nvbit_add_call_arg_reg_val(before, r, true);
        nvbit_insert_call(after, "bittu_post", IPOINT_AFTER); nvbit_add_call_arg_guard_pred_val(after);
        nvbit_add_call_arg_const_val64(after, (uint64_t)g_rec); nvbit_add_call_arg_const_val64(after, (uint64_t)g_nseen); nvbit_add_call_arg_const_val32(after, nth);
        nvbit_add_call_arg_const_val32(after, (int)g.res_regs.size()); for (int r : g.res_regs) nvbit_add_call_arg_reg_val(after, r, true);
        g_ready = true; (void)collect;
    }
}

static double median(std::vector<double> v) { if (v.empty()) return 0; std::sort(v.begin(), v.end()); return v[v.size() / 2]; }

void nvbit_at_cuda_event(CUcontext ctx, int is_exit, nvbit_api_cuda_t cbid, const char *name, void *params, CUresult *pStatus) {
    if (cbid != API_CUDA_cuLaunchKernel && cbid != API_CUDA_cuLaunchKernel_ptsz) return;
    cuLaunchKernel_params *p = (cuLaunchKernel_params *)params; CUfunction f = p->f;
    const bool mine = strstr(nvbit_get_func_name(ctx, f), kernel.c_str()) != nullptr;
    if (!is_exit) {
        ++launches;
        const int nth = (int)(p->gridDimX * p->gridDimY * p->gridDimZ * ((p->blockDimX * p->blockDimY * p->blockDimZ + 31) / 32 * 32));
        if (mine) {
            if (!done.size() || !g_ready) instrument(ctx, f, nth);
            if (g_ready && nth > g_nth) { fprintf(out, "launch %d: %d threads > %d allocated at the first launch: not recording\n", launches, nth, g_nth); nvbit_enable_instrumented(ctx, f, false); return; }
            if (g_ready) { cudaDeviceSynchronize(); cudaMemset(g_rec, 0, (size_t)g_nth * BITTU_INST * sizeof(BittuRec)); cudaMemset(g_nseen, 0, (size_t)g_nth * sizeof(int)); cudaDeviceSynchronize(); }
        }
        nvbit_enable_instrumented(ctx, f, mine && g_ready);
    } else if (mine && g_ready) {
        cudaDeviceSynchronize();
        cudaMemcpy(h_rec, g_rec, (size_t)g_nth * BITTU_INST * sizeof(BittuRec), cudaMemcpyDeviceToHost); cudaMemcpy(h_nseen, g_nseen, (size_t)g_nth * sizeof(int), cudaMemcpyDeviceToHost);
        std::vector<double> meas, ovh; long inst = 0, thr = 0, full = 0, bad_order = 0;
        for (int t = 0; t < g_nth; ++t) {
            if (h_nseen[t]) ++thr;
            for (int k = 0; k < h_nseen[t] && k < BITTU_INST; ++k) {
                const BittuRec &r = h_rec[t * BITTU_INST + k]; ++inst; full += r.mask_pre == 0xffffffffu;
                if (r.t1 < r.t0b || r.t0b < r.t0a) { ++bad_order; continue; }
                meas.push_back((double)(r.t1 - r.t0b)); ovh.push_back((double)(r.t0b - r.t0a));
            }
        }
        const double m = median(meas), o = median(ovh);
        fprintf(out, "launch %d: %ld threads ran the group, %ld instances, %ld with a full warp mask, %ld with clocks out of order\n", launches, thr, inst, full, bad_order);
        fprintf(out, "  group cycles (t1 - t0b): median %.0f, probe overhead o (t0b - t0a): median %.0f, corrected %.0f\n", m, o, m - o);
        int shown = 0;
        for (int t = 0; t < g_nth && shown < print_n; ++t) for (int k = 0; k < h_nseen[t] && k < BITTU_INST && shown < print_n; ++k, ++shown) {
            const BittuRec &r = h_rec[t * BITTU_INST + k];
            fprintf(out, "  thread %d inst %d t0a %llu t0b %llu t1 %llu ray", t, k, (unsigned long long)r.t0a, (unsigned long long)r.t0b, (unsigned long long)r.t1);
            for (int i = 0; i < 8; ++i) fprintf(out, " %08x", r.ray[i]); fprintf(out, " res");
            for (int i = 0; i < BITTU_MAXR; ++i) fprintf(out, " %08x", r.res[i]); fprintf(out, "\n");
        }
        fflush(out);
    }
}

void nvbit_at_term() { fprintf(out, "bittu compute: %d launches seen\n", launches); if (out != stderr) fclose(out); }
