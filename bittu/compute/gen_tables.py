"""Generate ttu_tables.h from the EoSS SM89 instruction tables (eoss.isa, ISASpec sm=89): opcodes and operand bit positions of the TTU classes.
    gen_tables.py > ttu_tables.h
Only field positions and opcodes are written (taken from the EoSS tables, not from NVIDIA code). BITTU's decoder uses these entries and nothing hand typed; the generator
also cross checks the opcodes against the ttu/encodings/ttu_sm89.json sequence (low 12 bits of each instruction) and exits non zero on a mismatch."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, ROOT)
from eoss.isa.model import ISASpec

CLASSES = [('ttuopen_', 'TTUOPEN'), ('ttumacrofuse_', 'TTUMACROFUSE'), ('ttust_', 'TTUST'), ('ttugo_', 'TTUGO'), ('ttuld__close', 'TTULD')]   # EoSS labels every SM89 TTULD ttuld__close; bit 74 ('*close') decides
KEEP = {'e': 'dual', 'Sb': 'fuse', 'Ra_offset': 'offset', 'Rb': 'rb', 'Rc': 'rc', 'Rd': 'rd', 'ntz': 'close', 'Pg': 'pg', 'Pg_not': 'pg_not'}
s = ISASpec.load(sm=89)
enc = json.load(open(os.path.join(ROOT, 'ttu', 'encodings', 'ttu_sm89.json')))
seq_ops = {int(i['lo'], 16) & 0xfff for q in enc['sequences'].values() for i in q['instructions']}


def rng(b):
    b = b if isinstance(b, list) else [b]
    out = []
    for x in b:
        hi, _, lo = x.partition('_'); out.append((int(hi), int(lo) if lo else int(hi)))
    return out


print('// generated by bittu/compute/gen_tables.py from the EoSS SM89 tables; do not edit')
print('#pragma once\n#include <stdint.h>\nstruct TtuField { int hi, lo; };')
print('struct TtuClass { const char *name; unsigned op12; TtuField dual, fuse, offset, rb, rc, rd, rd2, close, pg, pg_not; };')
rows = []
for cls, name in CLASSES:
    v = s.instructions[cls]; d = v.data; op = int(d['OPCODE'], 2) & 0xfff
    if op not in seq_ops: sys.exit('opcode 0x%x of %s not in ttu_sm89.json' % (op, cls))
    f = {k: (-1, -1) for k in ('dual', 'fuse', 'offset', 'rb', 'rc', 'rd', 'rd2', 'close', 'pg', 'pg_not')}
    for k, a in v.arguments.items():
        r = rng(a['bits'])
        if k in KEEP and len(r) == 1: f[KEEP[k]] = r[0]
        if cls == 'ttuld__close' and k == 'Rc': f['rd2'] = r[0]; f['rc'] = (-1, -1)    # SM89 names the second destination Rc; TTULD's Rd2
    rows.append((name, op, f))
print('static const TtuClass TTU_CLASSES[] = {')
for name, op, f in rows:
    print('  {"%s", 0x%x, %s},' % (name, op, ', '.join('{%d, %d}' % f[k] for k in ('dual', 'fuse', 'offset', 'rb', 'rc', 'rd', 'rd2', 'close', 'pg', 'pg_not'))))
print('};\nstatic const int TTU_NCLASSES = %d;' % len(rows))
